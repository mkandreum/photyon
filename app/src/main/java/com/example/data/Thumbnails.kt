package com.example.data

import android.content.Context
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.graphics.drawable.BitmapDrawable
import android.media.MediaMetadataRetriever
import android.os.Process
import android.util.LruCache
import android.util.Size
import coil.ImageLoader
import coil.decode.DataSource
import coil.fetch.DrawableResult
import coil.fetch.FetchResult
import coil.fetch.Fetcher
import coil.key.Keyer
import coil.request.Options
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.asCoroutineDispatcher
import kotlinx.coroutines.async
import kotlinx.coroutines.awaitAll
import kotlinx.coroutines.coroutineScope
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.withContext
import java.io.File
import java.util.UUID
import java.util.concurrent.Executors

/**
 * What a tile asks Coil for. [px] 0 is the small thumbnail kept on disk; larger values are mosaic hero
 * tiles, generated by the system at that size and held in memory only.
 */
data class Thumb(val item: MediaItem, val px: Int = 0) {
    val cacheKey: String get() = "t:${item.id}:${item.dateModifiedSec}:$px"
}

object Thumbnails {
    private const val DIR = "thumbs"
    private const val SMALL_PX = 384
    private const val PREFS = "thumbnails"
    private const val KEY_INITIAL_DONE = "initial_preload_done"

    data class Progress(val done: Int, val total: Int)

    private val _progress = MutableStateFlow<Progress?>(null)

    /** Non-null only during the very first build after install. */
    val progress: StateFlow<Progress?> = _progress.asStateFlow()

    /** Below-normal priority threads: the preload must never compete with the tiles on screen. */
    private val preloadDispatcher = Executors.newFixedThreadPool(2) { task ->
        Thread({
            Process.setThreadPriority(Process.THREAD_PRIORITY_BACKGROUND)
            task.run()
        }, "thumb-preload")
    }.asCoroutineDispatcher()

    private val ambient = LruCache<String, Int>(256)

    private fun dir(ctx: Context) = File(ctx.noBackupFilesDir, DIR).also { it.mkdirs() }

    private fun fileName(item: MediaItem) = "${item.id}_${item.dateModifiedSec}.jpg"

    private fun render(ctx: Context, item: MediaItem, px: Int): Bitmap =
        try {
            ctx.contentResolver.loadThumbnail(item.uri, Size(px, px), null)
        } catch (e: java.io.IOException) {
            // The system cannot thumbnail some videos; a frame of the video itself still can be read.
            if (item.isVideo) videoFrame(ctx, item, px) else throw e
        }

    private fun videoFrame(ctx: Context, item: MediaItem, px: Int): Bitmap {
        val retriever = MediaMetadataRetriever()
        try {
            retriever.setDataSource(ctx, item.uri)
            val w = item.width.coerceAtLeast(1)
            val h = item.height.coerceAtLeast(1)
            val scale = minOf(1f, px.toFloat() / minOf(w, h))
            return retriever.getScaledFrameAtTime(
                0L,
                MediaMetadataRetriever.OPTION_CLOSEST_SYNC,
                (w * scale).toInt().coerceAtLeast(1),
                (h * scale).toInt().coerceAtLeast(1)
            ) ?: error("no frame")
        } finally {
            retriever.release()
        }
    }

    /** Returns the disk thumbnail, creating it when missing. */
    private fun fileFor(ctx: Context, item: MediaItem): File {
        val out = File(dir(ctx), fileName(item))
        if (out.length() > 0) return out
        val bitmap = render(ctx, item, SMALL_PX)
        val tmp = File(out.parentFile, "${UUID.randomUUID()}.tmp")
        try {
            tmp.outputStream().use { bitmap.compress(Bitmap.CompressFormat.JPEG, 82, it) }
            if (!tmp.renameTo(out)) error("rename failed")
        } finally {
            tmp.delete()
            bitmap.recycle()
        }
        return out
    }

    /** Builds what is missing, newest first. Only the first run after install reports progress to the UI. */
    suspend fun preload(ctx: Context, items: List<MediaItem>) {
        if (items.isEmpty()) return
        val prefs = ctx.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
        val firstRun = !prefs.getBoolean(KEY_INITIAL_DONE, false)
        val existing = withContext(Dispatchers.IO) { dir(ctx).list()?.toHashSet() ?: hashSetOf() }
        val missing = items.filter { fileName(it) !in existing }
        try {
            if (firstRun && missing.isNotEmpty()) _progress.value = Progress(0, missing.size)
            var done = 0
            for (chunk in missing.chunked(32)) {
                coroutineScope {
                    chunk.map { item ->
                        async(preloadDispatcher) {
                            runCatching { fileFor(ctx, item) }
                                .onFailure { android.util.Log.w("Thumbnails", "${item.id}: ${it.message}") }
                        }
                    }.awaitAll()
                }
                done += chunk.size
                if (firstRun) _progress.value = Progress(done, missing.size)
            }
            prefs.edit().putBoolean(KEY_INITIAL_DONE, true).apply()
            prune(ctx, items)
        } finally {
            _progress.value = null
        }
    }

    private suspend fun prune(ctx: Context, items: List<MediaItem>) = withContext(Dispatchers.IO) {
        val wanted = items.mapTo(HashSet(items.size * 2)) { fileName(it) }
        dir(ctx).listFiles()?.forEach { if (it.name !in wanted) it.delete() }
    }

    /** Average color of the photo, for the viewer's ambient backdrop. Null until its thumbnail exists. */
    suspend fun ambientColor(ctx: Context, item: MediaItem): Int? = withContext(Dispatchers.IO) {
        ambient.get(item.id)?.let { return@withContext it }
        val file = File(dir(ctx), fileName(item))
        if (file.length() == 0L) return@withContext null
        val bitmap = BitmapFactory.decodeFile(file.path, BitmapFactory.Options().apply { inSampleSize = 16 })
            ?: return@withContext null
        val scaled = Bitmap.createScaledBitmap(bitmap, 1, 1, true)
        val color = scaled.getPixel(0, 0)
        if (scaled !== bitmap) scaled.recycle()
        bitmap.recycle()
        ambient.put(item.id, color)
        color
    }

    class ThumbFetcher(private val thumb: Thumb, private val options: Options) : Fetcher {
        override suspend fun fetch(): FetchResult {
            val ctx = options.context
            val bitmap = if (thumb.px > 0) {
                render(ctx, thumb.item, thumb.px)
            } else {
                BitmapFactory.decodeFile(fileFor(ctx, thumb.item).path)
                    ?: render(ctx, thumb.item, SMALL_PX)
            }
            // Uploading here keeps the texture upload off the UI thread while scrolling.
            val ready = bitmap.copy(Bitmap.Config.HARDWARE, false) ?: bitmap
            if (ready !== bitmap) bitmap.recycle()
            return DrawableResult(BitmapDrawable(ctx.resources, ready), isSampled = false, dataSource = DataSource.DISK)
        }

        class Factory : Fetcher.Factory<Thumb> {
            override fun create(data: Thumb, options: Options, imageLoader: ImageLoader): Fetcher =
                ThumbFetcher(data, options)
        }
    }

    class ThumbKeyer : Keyer<Thumb> {
        override fun key(data: Thumb, options: Options): String = data.cacheKey
    }
}
